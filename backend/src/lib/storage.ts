import path from "path";
import fs from "fs/promises";
import { randomBytes } from "crypto";
import { AppError } from "../middleware/errorHandler";
import { env } from "../config/env";

/**
 * File storage behind a narrow interface (brief working rule 4: secrets in
 * configuration, not code; brief 6.8 wants the same swappable-interface
 * discipline applied to geo).
 *
 * Only a local-disk driver is implemented for now. Uploaded files include
 * cancelled cheques and bank letters, so `local` keeps them outside the web
 * root and `readRef` is only ever reachable through an authenticated route
 * that re-checks ownership. STORAGE_DRIVER=s3 is reserved for the S3 driver
 * that will replace it — nothing else in the codebase needs to change.
 */

export interface StoredFile {
  /** Opaque, unguessable key handed to the database and to readers. */
  fileRef: string;
  fileName: string;
  mimeType: string;
  sizeBytes: number;
}

export interface StorageProvider {
  save(buffer: Buffer, opts: { fileName: string; mimeType: string; scope: string }): Promise<StoredFile>;
  read(fileRef: string): Promise<Buffer>;
  remove(fileRef: string): Promise<void>;
}

const ALLOWED_MIME = new Map<string, string>([
  ["application/pdf", ".pdf"],
  ["image/jpeg", ".jpg"],
  ["image/png", ".png"],
]);

export const UPLOAD_ACCEPTED_MIME = [...ALLOWED_MIME.keys()];

class LocalDiskStorage implements StorageProvider {
  constructor(private readonly root: string) {}

  private resolve(ref: string): string {
    // fileRef is generated by us, never accepted raw from a request body, but
    // normalise anyway so a crafted value cannot escape the root.
    const cleaned = path.normalize(ref).replace(/^(\.\.(\/|\\|$))+/, "");
    const full = path.join(this.root, cleaned);
    const rootWithSep = path.resolve(this.root) + path.sep;
    if (!path.resolve(full).startsWith(rootWithSep)) {
      throw new AppError("Invalid file reference", 400);
    }
    return full;
  }

  async save(
    buffer: Buffer,
    opts: { fileName: string; mimeType: string; scope: string },
  ): Promise<StoredFile> {
    const ext = ALLOWED_MIME.get(opts.mimeType) ?? ".bin";
    const dir = path.join(this.root, opts.scope);
    await fs.mkdir(dir, { recursive: true });

    const key = `${randomBytes(16).toString("hex")}${ext}`;
    await fs.writeFile(path.join(dir, key), buffer);

    return {
      fileRef: path.posix.join(opts.scope, key),
      fileName: opts.fileName,
      mimeType: opts.mimeType,
      sizeBytes: buffer.byteLength,
    };
  }

  async read(fileRef: string): Promise<Buffer> {
    return fs.readFile(this.resolve(fileRef));
  }

  async remove(fileRef: string): Promise<void> {
    try {
      await fs.unlink(this.resolve(fileRef));
    } catch {
      // Removing a file that is already gone is not an error worth failing on.
    }
  }
}

let provider: StorageProvider;

export function storage(): StorageProvider {
  if (!provider) {
    switch (env.storage.driver) {
      case "local":
        provider = new LocalDiskStorage(path.resolve(env.storage.localDir));
        break;
      case "s3":
        throw new AppError(
          "STORAGE_DRIVER=s3 is not implemented yet. Use STORAGE_DRIVER=local.",
          500,
        );
    }
  }
  return provider;
}